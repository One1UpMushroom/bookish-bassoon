"""Draws the driver board's schematic (KiCad 7) from design.py.

Run through build.py. The positions below are only the drawing: what is
connected to what comes from design.py, and check.py verifies that the nets
KiCad extracts from this file are exactly those.
"""
import design
from kisch import S, Schematic, SymbolLibs, Sym, font
from sexpr import dump

PROJECT = 'tasklamp-driver'
G = 2.54


def qtpy_symbol_lib():
    """The project's own symbol: the QT Py as one 14-pin module."""
    def pin(num, name, x, y, ang, etype='passive'):
        return S('pin', Sym(etype), Sym('line'), S('at', x, y, ang), S('length', 2.54),
                 S('name', name, font(1.27)), S('number', num, font(1.27)))

    gpio = {'A0': 'GP29', 'A1': 'GP28', 'A2': 'GP27', 'A3': 'GP26', 'SDA': 'GP24', 'SCL': 'GP25',
            'TX': 'GP20', 'RX': 'GP5', 'SCK': 'GP6', 'MI': 'GP4', 'MO': 'GP3'}
    pins = []
    for n in range(1, 8):       # left side, top to bottom
        name = design.QTPY_PINS[str(n)][0]
        pins.append(pin(str(n), '%s/%s' % (name, gpio[name]), -17.78, 7.62 - (n - 1) * G, 0))
    for n in range(8, 15):      # right side, bottom to top
        name = design.QTPY_PINS[str(n)][0]
        label = '%s/%s' % (name, gpio[name]) if name in gpio else name
        etype = 'power_out' if name == '3V' else 'passive'
        pins.append(pin(str(n), label, 17.78, -7.62 + (n - 8) * G, 180, etype))

    def prop(name, val, x, y, hide=False, just=None):
        return S('property', name, val, S('at', x, y, 0), font(1.27, justify=just, hide=hide))

    sym = S('symbol', 'QTPy_RP2040', S('pin_names', S('offset', 1.016)), S('in_bom', Sym('yes')),
            S('on_board', Sym('yes')),
            prop('Reference', 'U', -15.24, 11.43, just='left'),
            prop('Value', 'QTPy_RP2040', 0, -11.43),
            prop('Footprint', design.FP_QTPY, 0, -13.97, hide=True),
            prop('Datasheet', 'https://learn.adafruit.com/adafruit-qt-py-2040', 0, 0, hide=True),
            prop('ki_keywords', 'Adafruit QT Py RP2040 module', 0, 0, hide=True),
            prop('ki_description', 'Adafruit QT Py RP2040 on two 1x7 sockets, USB at pins 1 and 14', 0, 0,
                 hide=True),
            S('symbol', 'QTPy_RP2040_0_1',
              S('rectangle', S('start', -15.24, 10.16), S('end', 15.24, -10.16),
                S('stroke', S('width', 0.254), S('type', Sym('default'))),
                S('fill', S('type', Sym('background'))))),
            [Sym('symbol'), 'QTPy_RP2040_1_1'] + pins)
    return dump(S('kicad_symbol_lib', S('version', 20220914), S('generator', Sym('tasklamp_gen')), sym)) + '\n'


def build(sym_lib_path, date, rev):
    libs = SymbolLibs(extra={'TaskLamp': sym_lib_path})
    s = Schematic(libs, PROJECT, 'Task lamp driver board', rev, date, comments=(
        'Five 24 V strip channels switched by a QT Py RP2040',
        '0.8 m RGB tape + 1 m tunable-white tape, about 1 A in total',
        'Generated by tools/pcb from tools/pcb/design.py'))
    parts = {p['ref']: p for p in design.parts()}

    def put(ref, x, y, rot=0, mirror=None, **kw):
        p = parts[ref]
        fields = {}
        if p['mpn']:
            fields['MPN'] = p['mpn']
        if p['src']:
            fields['Source'] = p['src']
        return s.place(ref, p['sym'], x, y, rot=rot, mirror=mirror, value=p['value'], footprint=p['fp'],
                       in_bom=not ref.startswith(('H', 'TP')), extra_fields=fields, **kw)

    def pin(ref, n):
        return s.pin(ref, n)

    def check_net(ref, n, net):
        assert parts[ref]['pins'][str(n)] == net, (ref, n, net, parts[ref]['pins'][str(n)])

    # ------------------------------------------------------------------ 24 V input
    RAIL = 14 * G                      # y of the horizontal power rail
    s.text('24 V INPUT AND PROTECTION', 8 * G, 8 * G, 2.0, bold=True)
    put('J1', 10 * G, 15 * G, rot=180, ref_at=(-2.54, -6.35, 'left'), val_at=(-2.54, 5.08, 'left'))
    check_net('J1', 2, 'VIN')
    put('F1', 18 * G, RAIL, rot=270, ref_at=(0, -3.81, 'center'), val_at=(0, 3.81, 'center'))
    put('D7', 26 * G, RAIL, rot=180, ref_at=(0, -3.81, 'center'), val_at=(0, 3.81, 'center'))
    s.wire(pin('J1', 2), pin('F1', 2))
    s.label('VIN', pin('J1', 2)[0] + 1.27, RAIL)
    s.wire(pin('F1', 1), pin('D7', 2))
    s.label('VFUSE', pin('F1', 1)[0] + 0.635, RAIL)
    s.wire(pin('J1', 1), (pin('J1', 1)[0] + G, pin('J1', 1)[1]), (pin('J1', 1)[0] + G, 19 * G))
    s.power('power:GND', pin('J1', 1)[0] + G, 19 * G)

    # rail from the diode's cathode to the buck converter's input, with the shunt parts hanging off it
    put('D8', 31 * G, 17 * G, rot=270, ref_at=(2.54, -1.27, 'left'), val_at=(2.54, 1.27, 'left'))
    put('C1', 37 * G, 17 * G, ref_at=(2.54, -1.27, 'left'), val_at=(2.54, 1.27, 'left'))
    put('C2', 44 * G, 17 * G, ref_at=(2.54, -1.27, 'left'), val_at=(2.54, 1.27, 'left'))
    UBX, UBY = 67 * G, RAIL + 2 * G           # buck chip: its VIN pin lands on the rail
    put('U2', UBX, UBY, ref_at=(0, -11.43, 'center'), val_at=(2.54, 13.97, 'left'))
    assert abs(pin('U2', 2)[1] - RAIL) < 1e-6, pin('U2', 2)
    caps_in = (('C3', 51 * G), ('C4', 55 * G), ('C5', 59 * G))
    for ref, x in caps_in:
        put(ref, x, 17 * G, rot=180 if parts[ref]['pins']['1'] == 'GND' else 0,
            ref_at=(1.27, -1.27, 'left'), val_at=(1.27, 1.27, 'left'))
    taps = [31 * G, 37 * G, 44 * G, 49 * G] + [x for _, x in caps_in] + [62.5 * G]
    xs = [pin('D7', 1)[0]] + taps + [pin('U2', 2)[0]]
    for a, b in zip(xs, xs[1:]):
        s.wire((a, RAIL), (b, RAIL))
    for ref, x in (('D8', 31 * G), ('C1', 37 * G), ('C2', 44 * G)) + caps_in:
        top, bot = (1, 2) if parts[ref]['pins']['1'] == '+24V' else (2, 1)
        s.junction(x, RAIL)
        s.wire((x, RAIL), pin(ref, top))
        s.wire(pin(ref, bot), (x, 19 * G))
        s.power('power:GND', x, 19 * G)
    s.junction(49 * G, RAIL)
    s.wire((49 * G, RAIL), (49 * G, 12 * G))
    s.power('power:+24V', 49 * G, 12 * G)
    s.power('power:PWR_FLAG', 46.5 * G, RAIL)
    # EN tied to VIN
    en = pin('U2', 3)
    s.junction(62.5 * G, RAIL)
    s.wire(en, (62.5 * G, en[1]), (62.5 * G, RAIL))
    # chip ground, VCC capacitor, PG left open
    g = pin('U2', 1)
    s.wire(g, (g[0], g[1] + G))
    s.power('power:GND', g[0], g[1] + G)
    vcc = pin('U2', 6)
    put('C7', vcc[0], vcc[1] + 3 * G, ref_at=(1.27, -1.27, 'left'), val_at=(1.27, 1.27, 'left'))
    s.wire(vcc, pin('C7', 1))
    s.label('VCC', vcc[0], vcc[1] + 0.5 * G, angle=90)
    s.wire(pin('C7', 2), (vcc[0], vcc[1] + 5 * G))
    s.power('power:GND', vcc[0], vcc[1] + 5 * G)
    s.noconnect(*pin('U2', 4))

    # ------------------------------------------------------------------ 5 V supply
    s.text('5 V FOR THE CONTROLLER: LMR33630 BUCK (BUCK//33630 CIRCUIT)', 53 * G, 8 * G, 2.0, bold=True)
    boot, sw, fb = pin('U2', 7), pin('U2', 8), pin('U2', 5)
    put('C6', boot[0] + 3 * G, boot[1] + 1.5 * G, rot=180, ref_at=(1.27, -1.27, 'left'), val_at=(1.27, 1.27, 'left'))
    s.wire(boot, pin('C6', 2))
    s.label('BOOT', boot[0] + 0.635, boot[1])
    swx = sw[0] + 2 * G
    s.wire(sw, (swx, sw[1]))
    s.wire((swx, sw[1]), (swx, pin('C6', 1)[1]), pin('C6', 1))
    s.junction(swx, sw[1])
    VR = sw[1]                                  # the 5 V rail runs level with SW
    put('L1', 80 * G, VR, rot=90, ref_at=(0, -2.54, 'center'), val_at=(0, 2.54, 'center'))
    l_in, l_out = pin('L1', 1), pin('L1', 2)
    if l_in[0] > l_out[0]:
        l_in, l_out = l_out, l_in
    s.wire((swx, sw[1]), l_in)
    s.label('SW', swx + 1.27, sw[1])
    # feedback divider: R11 from the rail down to the FB node, R12 from there to ground
    put('R11', 84 * G, VR + 3.5 * G, rot=180, ref_at=(1.27, -1.27, 'left'), val_at=(1.27, 1.27, 'left'))
    fbn = (84 * G, VR + 5.75 * G)
    s.wire(pin('R11', 1), fbn)
    s.wire((84 * G, VR), pin('R11', 2))
    s.junction(84 * G, VR)
    s.junction(*fbn)
    put('R12', 87 * G, fbn[1], rot=270, ref_at=(0, -2.54, 'center'), val_at=(0, 2.54, 'center'))
    r12 = [pin('R12', 1), pin('R12', 2)]
    near, far = sorted(r12, key=lambda q: q[0])
    assert far == pin('R12', 1), 'R12: FB end must face the node'
    s.wire(fbn, near)
    s.wire(far, (far[0] + G, far[1]))
    s.power('power:GND', far[0] + G, far[1], rot=90)
    s.wire(fb, (fb[0] + G, fb[1]), (fb[0] + G, fbn[1]), fbn)
    s.label('FB', fb[0] + 0.3, fb[1])
    # output capacitors, test pad, +5V, and the diode to the QT Py
    outs = [('C8', 93 * G), ('C9', 97.5 * G), ('C10', 102 * G), ('C11', 106.5 * G)]
    for ref, x in outs:
        put(ref, x, VR + 3 * G, rot=0 if parts[ref]['pins']['1'] == '+5V' else 180,
            ref_at=(1.27, -1.27, 'left'), val_at=(1.27, 1.27, 'left'))
    put('TP1', 110 * G, VR, ref_at=(1.27, -3.81, 'left'), val_at=(1.27, -1.27, 'left'), hide_val=True)
    put('D6', 114 * G, VR, rot=180, ref_at=(0, -3.81, 'center'), val_at=(0, 3.81, 'center'))
    xs = [l_out[0], 84 * G, 90 * G] + [x for _, x in outs] + [110 * G, pin('D6', 2)[0]]
    for a, b in zip(xs, xs[1:]):
        s.wire((a, VR), (b, VR))
    for ref, x in outs:
        top, bot = (1, 2) if parts[ref]['pins']['1'] == '+5V' else (2, 1)
        s.junction(x, VR)
        s.wire((x, VR), pin(ref, top))
        s.wire(pin(ref, bot), (x, VR + 5 * G))
        s.power('power:GND', x, VR + 5 * G)
    s.junction(90 * G, VR)
    s.wire((90 * G, VR), (90 * G, VR - 3 * G))
    s.power('power:+5V', 90 * G, VR - 3 * G)
    s.junction(110 * G, VR)
    k = pin('D6', 1)
    s.wire(k, (k[0] + 2 * G, k[1]))
    s.label('QT_5V', k[0] + 0.635, k[1])

    # ------------------------------------------------------------------ controller
    UX, UY = 91 * G, 29 * G
    s.text('CONTROLLER', 40 * G, UY - 3.5 * G, 2.0, bold=True)
    put('U1', UX, UY, ref_at=(-15.24, -11.43, 'left'), val_at=(0, 12.7, 'center'))
    for n in range(1, 8):
        p = pin('U1', n)
        net = design.QTPY_PINS[str(n)][1]
        s.wire(p, (p[0] - 2 * G, p[1]))
        s.label(net, p[0] - 2 * G, p[1], angle=180, justify='right bottom')
    # right side: 5V, GND, 3V and the lines that run straight across to the display header
    p5 = pin('U1', 14)
    s.wire(p5, (p5[0] + 2 * G, p5[1]))
    s.label('QT_5V', p5[0] + 0.635, p5[1])
    pg = pin('U1', 13)
    s.wire(pg, (pg[0] + 5 * G, pg[1]))
    s.power('power:GND', pg[0] + 5 * G, pg[1], rot=90)

    JX = UX + 17.78 + 14 * G
    put('J4', JX, UY + 2 * G, mirror='y', ref_at=(1.27, -11.43, 'left'), val_at=(1.27, -8.89, 'left'))
    for i, net in enumerate(design.J4_PINS):
        check_net('J4', i + 1, net)
    straight = {'12': 1, '11': 2, '10': 3, '9': 4, '8': 5}     # U1 pad -> J4 pin on the same line
    for upin, jpin in straight.items():
        a, b = pin('U1', upin), pin('J4', jpin)
        assert abs(a[1] - b[1]) < 1e-6, (upin, jpin, a, b)
        net = design.QTPY_PINS[upin][1]
        if net == '+3V3':
            mid = a[0] + 9 * G
            s.wire(a, (mid, a[1]))
            s.wire((mid, a[1]), b)
            s.junction(mid, a[1])
            s.wire((mid, a[1]), (mid, a[1] - 3 * G))
            s.power('power:+3V3', mid, a[1] - 3 * G)
        else:
            s.wire(a, b)
            s.label(net, a[0] + 0.635, a[1])
    for jpin in (6, 7):
        p = pin('J4', jpin)
        s.wire(p, (p[0] - 3 * G, p[1]))
        s.label(design.J4_PINS[jpin - 1], p[0] - 3 * G, p[1], angle=180, justify='right bottom')
    p = pin('J4', 8)
    s.wire(p, (p[0] - 2 * G, p[1]), (p[0] - 2 * G, p[1] + G))
    s.power('power:GND', p[0] - 2 * G, p[1] + G)
    s.text('J4 carries seven wires to the TFT (3V, MOSI, SCK, LITE, CS, DC, GND)', 40 * G, UY - 1 * G, 1.27)
    s.text('and one to the encoder board (INT). The encoder itself plugs into the', 40 * G, UY + 0.2 * G, 1.27)
    s.text("QT Py's STEMMA QT socket. U1 pin numbers: 1-7 down the left side from", 40 * G, UY + 1.4 * G, 1.27)
    s.text('the USB socket, 8-14 back up the right side.', 40 * G, UY + 2.6 * G, 1.27)

    # ------------------------------------------------------------------ strip switches
    QY = 47 * G
    s.text('STRIP SWITCHES  (five identical: gate resistor, pull-down, MOSFET, clamp diode)',
           8 * G, QY - 11.5 * G, 2.0, bold=True)
    for i, ch in enumerate(design.CHANNELS):
        n = i + 1
        qx = 18 * G + i * 17 * G
        rg, rpd, q, d = 'R%d' % n, 'R%d' % (n + 5), 'Q%d' % n, 'D%d' % n
        put(q, qx, QY, ref_at=(5.08, -1.27, 'left'), val_at=(5.08, 1.27, 'left'))
        put(rg, qx - 6 * G, QY, rot=90, ref_at=(0, -2.54, 'center'), val_at=(0, 2.54, 'center'))
        put(rpd, qx - 3 * G, QY + 3 * G, rot=180, ref_at=(-2.54, -1.27, 'right'), val_at=(-2.54, 1.27, 'right'))
        put(d, qx + G, QY - 7 * G, rot=270, ref_at=(2.54, -1.27, 'left'), val_at=(2.54, 1.27, 'left'))
        check_net(rg, 1, 'PWM_' + ch)
        check_net(rpd, 2, 'GATE_' + ch)
        check_net(d, 1, '+24V')
        node = (qx - 3 * G, QY)
        s.wire(pin(rg, 2), node)
        s.wire(node, pin(q, 1))
        s.junction(*node)
        s.wire(node, pin(rpd, 2))
        s.wire((node[0], QY - 1.5 * G), node)
        s.label('GATE_' + ch, node[0], QY - 1.5 * G, justify='left bottom')
        # input
        a = pin(rg, 1)
        s.wire(a, (a[0] - 2 * G, a[1]))
        s.label('PWM_' + ch, a[0] - 2 * G, a[1], angle=180, justify='right bottom')
        # ground
        gy = QY + 5 * G
        s.wire(pin(rpd, 1), (qx - 3 * G, gy))
        s.power('power:GND', qx - 3 * G, gy)
        s.wire(pin(q, 3), (qx + G, gy))
        s.power('power:GND', qx + G, gy)
        # drain: up to the clamp, and off to the terminal
        tap = (qx + G, QY - 4 * G)
        s.wire(pin(q, 2), tap)
        s.wire(tap, pin(d, 2))
        s.junction(*tap)
        s.wire(tap, (tap[0] + 3 * G, tap[1]))
        s.label('OUT_' + ch, tap[0] + 0.635, tap[1])
        s.power('power:+24V', *pin(d, 1))

    # ------------------------------------------------------------------ strip terminals
    TX = 104 * G
    s.text('TO THE STRIPS', TX - 10 * G, 39.5 * G, 2.0, bold=True)
    for ref, y0 in (('J3', 44 * G), ('J2', 52 * G)):
        put(ref, TX, y0, ref_at=(-1.27, -6.35, 'left'), val_at=(3.81, 0, 'left'))
        pins = parts[ref]['pins']
        for num in sorted(pins, key=int):
            p = pin(ref, num)
            if pins[num] == '+24V':
                s.wire(p, (p[0] - 7 * G, p[1]), (p[0] - 7 * G, p[1] - G))
                s.power('power:+24V', p[0] - 7 * G, p[1] - G)
            else:
                s.wire(p, (p[0] - 3 * G, p[1]))
                s.label(pins[num], p[0] - 3 * G, p[1], angle=180, justify='right bottom')

    # ------------------------------------------------------------------ mechanical
    s.text('MOUNTING HOLES AND TEST PADS', 8 * G, 59.5 * G, 2.0, bold=True)
    for n in range(1, 5):
        put('H%d' % n, (10 + 5 * (n - 1)) * G, 63 * G, ref_at=(0, -3.81, 'center'), val_at=(0, 3.81, 'center'))
    put('TP2', 33 * G, 63 * G, ref_at=(1.27, -3.81, 'left'), val_at=(1.27, -1.27, 'left'), hide_val=True)
    s.wire(pin('TP2', 1), (33 * G, 64 * G))
    s.power('power:GND', 33 * G, 64 * G)
    s.wire(pin('TP2', 1), (38 * G, 63 * G))
    s.power('power:PWR_FLAG', 38 * G, 63 * G)

    s.text('Loads at 100 %:  red, green, blue about 0.13 A each;  warm, cool about 0.30 A each;  everything on about 1.0 A.',
           40 * G, 62 * G, 1.27)
    s.text('The gates are driven straight from the 3.3 V pins. At these currents an IRLB8721 is fully on;',
           40 * G, 63.2 * G, 1.27)
    s.text('confirm it once: with a channel at 100 %, drain to source must read under 0.1 V.',
           40 * G, 64.4 * G, 1.27)
    return s.render()


